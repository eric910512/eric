"""Private photo storage (皮膚照片 Phase 1b; docs/skin-photo-storage-design.md, docs/skin-photo-deployment.md).

The image bytes never go to the database or to a public folder. One interface, two backends:

- ``LocalPrivateStorage``: files under a private directory (default ``<instance>/private-photos``,
  git-ignored). **Development and tests only** — refused in staging / production, where Render's disk is
  temporary and shared with the app.
- ``PrivateObjectStorage``: an S3-compatible private bucket with a customer-managed KMS key (candidate for
  the hospital's production environment). The adapter is complete but nothing here creates a bucket or
  credentials; it needs every PHOTO_OBJECT_* setting and the ``boto3`` package, otherwise photos stay off.

``photo_feature_status`` decides whether uploads / viewing are on. An unusable configuration disables
the feature — it never falls back to another (less safe) backend.
"""

import importlib.util
import os
import re
import tempfile
from dataclasses import dataclass

from app.config import PRODUCTION_LIKE

# storage keys are generated by the server only: photos/<32 hex>/(full|thumb).jpg — never a file name
KEY_PATTERN = re.compile(r"^photos/[0-9a-f]{32}/(full|thumb)\.jpg$")


class PhotoStorageError(Exception):
    """The storage backend failed (the caller answers 503 / compensates)."""


class PhotoStorageService:
    name = None

    @staticmethod
    def check_key(key):
        if not isinstance(key, str) or not KEY_PATTERN.match(key):
            raise ValueError("invalid photo storage key")

    def put(self, key, data, content_type):
        raise NotImplementedError

    def get(self, key):
        raise NotImplementedError

    def delete(self, key):
        """Remove an object; deleting a missing object is not an error."""
        raise NotImplementedError

    def exists(self, key):
        raise NotImplementedError


class LocalPrivateStorage(PhotoStorageService):
    """Development / tests only (see module docstring)."""

    name = "local"

    def __init__(self, root):
        self.root = os.path.realpath(root)  # created on the first write (start-up / CLI commands create nothing)

    def _path(self, key):
        self.check_key(key)
        path = os.path.realpath(os.path.join(self.root, *key.split("/")))
        if not path.startswith(self.root + os.sep):  # belt and braces: the pattern already forbids "..", "/", "\\"
            raise ValueError("invalid photo storage key")
        return path

    def put(self, key, data, content_type):
        path = self._path(key)
        os.makedirs(os.path.dirname(path), mode=0o700, exist_ok=True)
        try:
            fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".upload-")
            with os.fdopen(fd, "wb") as f:
                f.write(data)
            os.replace(tmp, path)  # atomic: a reader never sees half a file
        except OSError as exc:
            raise PhotoStorageError("local storage write failed") from exc

    def get(self, key):
        try:
            with open(self._path(key), "rb") as f:
                return f.read()
        except FileNotFoundError:
            return None
        except OSError as exc:
            raise PhotoStorageError("local storage read failed") from exc

    def delete(self, key):
        path = self._path(key)
        try:
            os.remove(path)
        except FileNotFoundError:
            pass
        except OSError as exc:
            raise PhotoStorageError("local storage delete failed") from exc
        try:
            os.rmdir(os.path.dirname(path))  # the photo's own folder, once both variants are gone
        except OSError:
            pass

    def exists(self, key):
        return os.path.isfile(self._path(key))

    def keys(self):
        """Every stored key (`flask photos verify` / tests)."""
        out = []
        base = os.path.join(self.root, "photos")
        for folder in os.listdir(base) if os.path.isdir(base) else []:
            for name in os.listdir(os.path.join(base, folder)):
                key = f"photos/{folder}/{name}"
                if KEY_PATTERN.match(key):
                    out.append(key)
        return sorted(out)


class PrivateObjectStorage(PhotoStorageService):
    """S3-compatible private bucket, server-side encryption with a customer-managed KMS key.

    Never connected in this repository's tests (a fake client is injected). Requires ``boto3``, which is
    not a dependency yet: add it together with the hospital's storage decision (docs/skin-photo-deployment.md).
    """

    name = "object"
    REQUIRED = ("PHOTO_OBJECT_BUCKET", "PHOTO_OBJECT_REGION", "PHOTO_OBJECT_KMS_KEY_ID",
                "PHOTO_OBJECT_ACCESS_KEY_ID", "PHOTO_OBJECT_SECRET_ACCESS_KEY")

    def __init__(self, config, client=None):
        self.bucket = config.get("PHOTO_OBJECT_BUCKET")
        self.region = config.get("PHOTO_OBJECT_REGION")
        self.endpoint_url = config.get("PHOTO_OBJECT_ENDPOINT_URL") or None
        self.kms_key_id = config.get("PHOTO_OBJECT_KMS_KEY_ID")
        self._access_key = config.get("PHOTO_OBJECT_ACCESS_KEY_ID")
        self._secret_key = config.get("PHOTO_OBJECT_SECRET_ACCESS_KEY")
        self._client = client

    @classmethod
    def missing_settings(cls, config):
        return [name for name in cls.REQUIRED if not config.get(name)]

    @staticmethod
    def sdk_available():
        return importlib.util.find_spec("boto3") is not None

    def _s3(self):
        if self._client is None:
            import boto3  # noqa: PLC0415 — optional, only with a configured bucket

            self._client = boto3.client(
                "s3", region_name=self.region, endpoint_url=self.endpoint_url,
                aws_access_key_id=self._access_key, aws_secret_access_key=self._secret_key,
            )
        return self._client

    def put(self, key, data, content_type):
        self.check_key(key)
        try:
            self._s3().put_object(Bucket=self.bucket, Key=key, Body=data, ContentType=content_type,
                                  CacheControl="private, no-store", ServerSideEncryption="aws:kms", SSEKMSKeyId=self.kms_key_id)
        except Exception as exc:  # noqa: BLE001 — any SDK / network error: the caller compensates
            raise PhotoStorageError("object storage write failed") from exc

    def get(self, key):
        self.check_key(key)
        try:
            return self._s3().get_object(Bucket=self.bucket, Key=key)["Body"].read()
        except Exception as exc:  # noqa: BLE001
            if getattr(exc, "response", {}).get("Error", {}).get("Code") in ("NoSuchKey", "404"):
                return None
            raise PhotoStorageError("object storage read failed") from exc

    def delete(self, key):
        self.check_key(key)
        try:
            self._s3().delete_object(Bucket=self.bucket, Key=key)
        except Exception as exc:  # noqa: BLE001
            raise PhotoStorageError("object storage delete failed") from exc

    def exists(self, key):
        self.check_key(key)
        try:
            self._s3().head_object(Bucket=self.bucket, Key=key)
            return True
        except Exception as exc:  # noqa: BLE001
            if getattr(exc, "response", {}).get("Error", {}).get("Code") in ("NoSuchKey", "404", "NotFound"):
                return False
            raise PhotoStorageError("object storage check failed") from exc


# ------------------------------------------------------------------ feature switch


@dataclass
class PhotoFeature:
    upload_enabled: bool
    view_enabled: bool  # stored photos can be read (storage usable), even when new uploads are off
    reason: str | None  # why uploads are off (machine code; the UI shows a generic message)
    storage: PhotoStorageService | None


def _build_storage(app):
    config_name = app.config.get("CONFIG_NAME")
    backend = (app.config.get("PHOTO_STORAGE_BACKEND") or "").strip().lower()
    if backend == "local":
        if config_name in PRODUCTION_LIKE:
            return None, "local_storage_not_allowed"
        root = app.config.get("PHOTO_LOCAL_DIR")
        if not root:
            root = tempfile.mkdtemp(prefix="ccp-photos-") if app.testing else os.path.join(app.instance_path, "private-photos")
        return LocalPrivateStorage(root), None
    if backend == "object":
        if PrivateObjectStorage.missing_settings(app.config) or not PrivateObjectStorage.sdk_available():
            return None, "object_storage_not_configured"
        return PrivateObjectStorage(app.config), None
    return None, "no_storage_backend"


def init_photos(app):
    """Decide once at start-up; ``photo_feature(app)`` reads the result."""
    from app.modules.photo.consent import CONSENT_VERSION

    storage, problem = _build_storage(app)
    reason = None
    if not app.config.get("PHOTO_UPLOADS_ENABLED"):
        reason = "disabled_by_config"
    elif problem:
        reason = problem
    elif app.config.get("CONFIG_NAME") in PRODUCTION_LIKE and app.config.get("PHOTO_CONSENT_APPROVED_VERSION") != CONSENT_VERSION:
        reason = "consent_not_approved"  # staging / production: only a hospital-approved consent text
    app.extensions["photo_feature"] = PhotoFeature(
        upload_enabled=reason is None, view_enabled=storage is not None, reason=reason, storage=storage,
    )


def photo_feature(app):
    return app.extensions["photo_feature"]
